-- ---------------------------------------------------------------- Acceso y usuarios
CREATE TABLE rol (
    id_rol  INTEGER     PRIMARY KEY,
    nombre  VARCHAR(30) NOT NULL UNIQUE
);

INSERT INTO rol (id_rol, nombre) VALUES
    (1, 'Administrador'),
    (2, 'Encargado de ventas');

CREATE TABLE usuario (
    id_usuario      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_rol          INTEGER      NOT NULL REFERENCES rol (id_rol),
    nombre_completo VARCHAR(100) NOT NULL,
    nombre_usuario  VARCHAR(50)  NOT NULL UNIQUE,
    contrasena_hash VARCHAR(255) NOT NULL,
    estado          VARCHAR(10)  NOT NULL DEFAULT 'activo' CHECK (estado IN ('activo', 'inactivo')),
    fecha_registro  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- ---------------------------------------------------------------- Inventario
CREATE TABLE producto (
    id_producto             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo_producto         VARCHAR(50)   NOT NULL UNIQUE,
    nombre                  VARCHAR(100)  NOT NULL,
    presentacion            VARCHAR(80)   NOT NULL,
    laboratorio             VARCHAR(80)   NOT NULL,
    precio_venta            NUMERIC(12,2) NOT NULL CHECK (precio_venta >= 0),
    stock_minimo            INTEGER       NOT NULL CHECK (stock_minimo >= 0),
    dias_alerta_vencimiento INTEGER       NOT NULL CHECK (dias_alerta_vencimiento >= 0),
    estado                  VARCHAR(10)   NOT NULL DEFAULT 'activo' CHECK (estado IN ('activo', 'inactivo')),
    fecha_registro          TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE proveedor (
    id_proveedor INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre       VARCHAR(120) NOT NULL,
    telefono     VARCHAR(20)  NOT NULL,
    correo       VARCHAR(120),
    estado       VARCHAR(10)  NOT NULL DEFAULT 'activo' CHECK (estado IN ('activo', 'inactivo'))
);

CREATE TABLE lote (
    id_lote             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_producto         INTEGER     NOT NULL REFERENCES producto (id_producto),
    codigo_lote         VARCHAR(40) NOT NULL,
    fecha_vencimiento   DATE        NOT NULL,
    cantidad_disponible INTEGER     NOT NULL CHECK (cantidad_disponible >= 0),
    CONSTRAINT uq_lote_producto_codigo UNIQUE (id_producto, codigo_lote)
);
CREATE INDEX idx_lote_vencimiento ON lote (fecha_vencimiento);

CREATE TABLE entrada_inventario (
    id_entrada   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_lote      INTEGER   NOT NULL REFERENCES lote (id_lote),
    id_proveedor INTEGER   NOT NULL REFERENCES proveedor (id_proveedor),
    id_usuario   INTEGER   NOT NULL REFERENCES usuario (id_usuario),
    cantidad     INTEGER   NOT NULL CHECK (cantidad > 0),
    fecha_hora   TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE salida_inventario (
    id_salida   INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_lote     INTEGER      NOT NULL REFERENCES lote (id_lote),
    id_usuario  INTEGER      NOT NULL REFERENCES usuario (id_usuario),
    cantidad    INTEGER      NOT NULL CHECK (cantidad > 0),
    motivo      VARCHAR(15)  NOT NULL CHECK (motivo IN ('vencimiento', 'dano', 'otro')),
    observacion VARCHAR(200),
    fecha_hora  TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- ---------------------------------------------------------------- Ventas y devoluciones
CREATE TABLE venta (
    id_venta             INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,   -- tambien es el numero de comprobante (RF-08)
    id_usuario           INTEGER       NOT NULL REFERENCES usuario (id_usuario),
    fecha_hora           TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    total                NUMERIC(12,2) NOT NULL CHECK (total >= 0),
    estado               VARCHAR(12)   NOT NULL DEFAULT 'registrada' CHECK (estado IN ('registrada', 'anulada')),
    motivo_anulacion     VARCHAR(200),
    fecha_hora_anulacion TIMESTAMP,
    id_usuario_anula     INTEGER REFERENCES usuario (id_usuario)
);
CREATE INDEX idx_venta_fecha ON venta (fecha_hora);

CREATE TABLE detalle_venta (
    id_detalle_venta INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_venta         INTEGER       NOT NULL REFERENCES venta (id_venta),
    id_producto      INTEGER       NOT NULL REFERENCES producto (id_producto),
    cantidad         INTEGER       NOT NULL CHECK (cantidad > 0),
    precio_unitario  NUMERIC(12,2) NOT NULL CHECK (precio_unitario >= 0),
    subtotal         NUMERIC(12,2) NOT NULL CHECK (subtotal >= 0)
);
CREATE INDEX idx_detalle_venta_venta ON detalle_venta (id_venta);

CREATE TABLE detalle_venta_lote (
    id_detalle_venta INTEGER NOT NULL REFERENCES detalle_venta (id_detalle_venta),
    id_lote          INTEGER NOT NULL REFERENCES lote (id_lote),
    cantidad         INTEGER NOT NULL CHECK (cantidad > 0),
    PRIMARY KEY (id_detalle_venta, id_lote)
);

CREATE TABLE devolucion (
    id_devolucion  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_venta       INTEGER       NOT NULL REFERENCES venta (id_venta),
    id_usuario     INTEGER       NOT NULL REFERENCES usuario (id_usuario),
    fecha_hora     TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP,
    motivo         VARCHAR(200)  NOT NULL,
    valor_devuelto NUMERIC(12,2) NOT NULL CHECK (valor_devuelto >= 0)
);

CREATE TABLE detalle_devolucion (
    id_detalle_devolucion INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_devolucion         INTEGER       NOT NULL REFERENCES devolucion (id_devolucion),
    id_detalle_venta      INTEGER       NOT NULL REFERENCES detalle_venta (id_detalle_venta),
    id_lote               INTEGER       NOT NULL REFERENCES lote (id_lote),
    cantidad              INTEGER       NOT NULL CHECK (cantidad > 0),
    destino               VARCHAR(10)   NOT NULL CHECK (destino IN ('reintegro', 'baja')),
    valor                 NUMERIC(12,2) NOT NULL CHECK (valor >= 0)
);

-- ---------------------------------------------------------------- Clientes frecuentes y pedidos
CREATE TABLE cliente_frecuente (
    id_cliente     INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre         VARCHAR(100) NOT NULL,
    telefono       VARCHAR(20)  NOT NULL,
    fecha_registro TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE pedido (
    id_pedido      INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_cliente     INTEGER REFERENCES cliente_frecuente (id_cliente),
    nombre_cliente VARCHAR(100) NOT NULL,
    telefono       VARCHAR(20)  NOT NULL,
    fecha          DATE         NOT NULL,
    origen         VARCHAR(12)  NOT NULL CHECK (origen IN ('whatsapp', 'llamada', 'presencial')),
    modalidad      VARCHAR(10)  NOT NULL CHECK (modalidad IN ('domicilio', 'recoge')),
    direccion      VARCHAR(150),
    observaciones  VARCHAR(250),
    id_usuario     INTEGER      NOT NULL REFERENCES usuario (id_usuario),
    fecha_registro TIMESTAMP    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_pedido_direccion CHECK (modalidad <> 'domicilio' OR direccion IS NOT NULL)
);

CREATE TABLE detalle_pedido (
    id_detalle_pedido INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_pedido         INTEGER NOT NULL REFERENCES pedido (id_pedido),
    id_producto       INTEGER NOT NULL REFERENCES producto (id_producto),
    cantidad          INTEGER NOT NULL CHECK (cantidad > 0)
);

-- ---------------------------------------------------------------- Movimientos financieros
CREATE TABLE movimiento_financiero (
    id_movimiento  INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo           VARCHAR(10)   NOT NULL CHECK (tipo IN ('ingreso', 'egreso')),
    concepto       VARCHAR(150)  NOT NULL,
    id_proveedor   INTEGER REFERENCES proveedor (id_proveedor),
    fecha          DATE          NOT NULL,
    valor          NUMERIC(12,2) NOT NULL CHECK (valor > 0),
    id_usuario     INTEGER       NOT NULL REFERENCES usuario (id_usuario),
    fecha_registro TIMESTAMP     NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_movimiento_fecha ON movimiento_financiero (fecha);
