-- =============================================================================
-- Levi Plus - Esquema de base de datos (PostgreSQL)
-- Modelo logico de 16 tablas (documento ingenieril, seccion 2.1).
-- Los ENUM del modelo se implementan como VARCHAR con restriccion CHECK.
-- Existencias: se controlan por lote; el stock de un producto es la suma de sus lotes.
-- Ejecucion: docker compose lo carga solo en desarrollo; en Neon se ejecuta una vez
-- desde su editor SQL.
